import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** Install the optional quest UI without importing navigation or time setup. */
export default function installQuestSystem(rootFolder: string) {
    const source = fileURLToPath(new URL("../../templates/plugins/quest-system/", import.meta.url));
    const write = (file: string, content: string) => {
        const target = path.join(rootFolder, file);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, content);
    };
    const edit = (file: string, update: (content: string) => string) => {
        const target = path.join(rootFolder, file);
        if (!fs.existsSync(target)) throw new Error(`Quest System requires ${file}`);
        write(file, update(fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n")));
    };
    for (const file of fs.readdirSync(path.join(source, "src"), { recursive: true })) {
        const relative = String(file);
        const from = path.join(source, "src", relative);
        const target = path.join(rootFolder, "src", relative);
        if (fs.statSync(from).isFile() && !fs.existsSync(target)) {
            write(path.join("src", relative), fs.readFileSync(from, "utf8"));
        }
    }
    edit("src/routes/__root.tsx", (content) => {
        if (content.includes("<MemoMenu")) return content;
        return `import { MemoMenu } from "@/components/menus/memo-menu";\n${content}`.replace(
            "<SettingsDialogue />",
            "<SettingsDialogue />\n                <MemoMenu />",
        );
    });
    const quickTools = "src/components/quick-tools.tsx";
    if (fs.existsSync(path.join(rootFolder, quickTools))) {
        edit(quickTools, (content) => {
            if (content.includes('t("quests")')) return content;
            return content
                .replace(
                    "    const setHistory =",
                    '    const setMemo = useSetSearchParamState<boolean>("memo");\n    const setHistory =',
                )
                .replace(
                    '{t("back")}\n            </Button>',
                    `{t("back")}\n            </Button>\n            <Button variant="ghost" size="xs" className="h-5 px-1 text-[10px] sm:h-6 sm:px-2 sm:text-xs" onClick={() => setMemo(true)}>{t("quests")}</Button>`,
                );
        });
    } else {
        edit("src/components/screens/narration/narration-menubar.tsx", (content) => {
            if (content.includes('t("quests")')) return content;
            return `import { Button } from "@/components/ui/button";\n${content}`
                .replace(
                    "    const setSaves =",
                    '    const setMemo = useSetSearchParamState<boolean>("memo");\n    const setSaves =',
                )
                .replace(
                    "<ThemeModeToggle",
                    '<Button variant="ghost" size="sm" onClick={() => setMemo(true)}>{t("quests")}</Button>\n                <ThemeModeToggle',
                );
        });
    }
    edit("vite.config.ts", (content) => {
        if (content.includes("vitePluginNqtr(")) return content;
        return `import { vitePluginNqtr } from "@drincs/nqtr/vite";\n${content}`.replace(
            "        VitePWA(",
            '        vitePluginNqtr({ quests: "./src/content/quests/*.quest.{ts,tsx}", typeFilePath: "./src/nqtr.keys.gen.ts" }),\n        VitePWA(',
        );
    });
    if (!fs.existsSync(path.join(rootFolder, "src/nqtr.keys.gen.ts"))) {
        write(
            "src/nqtr.keys.gen.ts",
            "// Generated by the NQTR Vite plugin.\nexport const nqtrQuestIds = [] as const;\n",
        );
    }
    const ink = "src/content/ink/hashtag-commands.ts";
    if (fs.existsSync(path.join(rootFolder, ink))) {
        edit(ink, (content) =>
            content.includes("createNqtrHandler(")
                ? content
                : `import { createNqtrHandler } from "@drincs/nqtr/ink";\nimport { nqtrQuestIds } from "@/nqtr.keys.gen";\n${content}\ncreateNqtrHandler({ questIds: nqtrQuestIds, sections: { quest: true } });\n`,
        );
    }
    const translations = JSON.parse(
        fs.readFileSync(path.join(source, "translations.json"), "utf8"),
    );
    const locales = path.join(rootFolder, "src/locales");
    for (const file of fs.readdirSync(locales).filter((name) => name.endsWith(".json"))) {
        edit(`src/locales/${file}`, (content) => {
            const locale = JSON.parse(content);
            locale.ui = { ...translations, ...locale.ui };
            return `${JSON.stringify(locale, null, 2)}\n`;
        });
    }
    edit("AGENTS.md", (content) => {
        const entries = [
            "- `src/content/quests/`: quests of the game. It is recommended to create one file for each quest.",
            "- `src/pixi-vn.d.ts`: game-specific Pixi’VN type extensions.",
            "- `src/nqtr.d.ts`: game-specific quest interface extensions.",
            "- `src/nqtr.keys.gen.ts`: quest IDs generated by the NQTR Vite plugin; update quest source files instead of editing this file.",
        ].filter((entry) => !content.includes(entry.split("`:")[0] + "`:"));
        return entries.length
            ? content.replace(
                  "## Project structure",
                  `## Project structure\n\n${entries.join("\n")}`,
              )
            : content;
    });
}
